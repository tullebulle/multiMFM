#!/usr/bin/env python
"""Insert the regenerated-DNA cells into notebooks 02 and 03.

The user's notebook numbering follows the plan's §5 table: notebook 09 is Evo 2 / Table 6 only,
Fig 6 and Table 16 belong in ``02_dna_base_model.ipynb``, and Figs 7 and 8 plus Tables 4/5 and the
App. B.1 clustering statistic belong in ``03_dna_cyclizability.ipynb``. Those two notebooks are
owned by the rerun agent, so the cells were extracted into

    results/dna/regen/notebook_cells_for_02_03.json

rather than written into them directly. This script splices them in.

    python scripts/dna/regen/insert_regen_cells.py --dry-run      # show what would change
    python scripts/dna/regen/insert_regen_cells.py --notebook 02  # just one
    python scripts/dna/regen/insert_regen_cells.py                # both

It is conservative and idempotent:

* it appends, never overwrites, and refuses if the marker cell is already present;
* it adds the shared setup cell (imports, ``G``, ``FIGDIR``, ``save_paper_figure``) only if that
  notebook does not already define ``save_paper_figure``;
* it writes a ``.bak`` beside each notebook before touching it;
* the inserted cells are unexecuted, so run nbconvert afterwards:
  ``cd notebooks && jupyter nbconvert --to notebook --execute --inplace \\
      --ExecutePreprocessor.kernel_name=multimfm 02_dna_base_model.ipynb``

Every inserted cell degrades gracefully while the runs are still queued: each prints a "pending"
line and returns instead of raising, so the host notebook keeps executing.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
PAYLOAD = REPO / "results" / "dna" / "regen" / "notebook_cells_for_02_03.json"
TARGETS = {
    "02": REPO / "notebooks" / "02_dna_base_model.ipynb",
    "03": REPO / "notebooks" / "03_dna_cyclizability.ipynb",
}
MARKER = "<!-- dna-regen:inserted -->"


def _marker_cell(title: str) -> dict:
    text = (
        f"{MARKER}\n\n"
        f"---\n# {title}\n\n"
        "Regenerated by the `dna-regen` area on the parent-disjoint checkpoints, because the published "
        "outputs were lost in the netscratch purge. Provenance, Slurm job ids and the device each number "
        "was produced on: `results/dna/regen/PROVENANCE.md`. Cells print `pending` until the runs land; "
        "`bash scripts/dna/regen/collect.sh` fills them in and re-executes."
    )
    return {"cell_type": "markdown", "metadata": {}, "source": text.splitlines(keepends=True)}


def insert(key: str, dry_run: bool = False) -> str:
    payload = json.loads(PAYLOAD.read_text())
    target = TARGETS[key]
    if not target.exists():
        return f"{key}: {target.name} not found"
    nb = json.loads(target.read_text())
    existing = "".join("".join(c["source"]) for c in nb["cells"])
    if MARKER in existing:
        return f"{key}: already inserted (marker present) -- nothing to do"

    section = payload[f"notebook_{key}"]
    new: list[dict] = [_marker_cell(section["title"])]
    if "save_paper_figure" not in existing:
        new = payload["setup_additions"]["cells"] + new
    new += section["cells"]

    if dry_run:
        heads = [("".join(c["source"]).strip().split("\n")[0])[:70] for c in new]
        return f"{key}: would append {len(new)} cells to {target.name}:\n    " + "\n    ".join(heads)

    shutil.copy2(target, target.with_suffix(".ipynb.bak"))
    nb["cells"].extend(new)
    target.write_text(json.dumps(nb, indent=1) + "\n")
    return f"{key}: appended {len(new)} cells to {target.name} (backup at {target.name}.bak)"


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--notebook", choices=sorted(TARGETS), action="append",
                   help="which notebook to touch; repeatable, default both")
    p.add_argument("--dry-run", action="store_true")
    a = p.parse_args(argv)
    for key in a.notebook or sorted(TARGETS):
        print(insert(key, dry_run=a.dry_run))


if __name__ == "__main__":
    main()
